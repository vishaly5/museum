  function encodePath(path) {
    return path.split("/").map(encodeURIComponent).join("/");
  }

  function addLanguageOption() {
    var selector = document.getElementById("languageSelector");
    if (selector && !selector.querySelector('option[value="kannada"]')) {
      selector.insertAdjacentHTML("beforeend", '<option value="kannada">ಕನ್ನಡ (Kannada)</option>');
    }
    return selector;
  }

  function renderOverview(selector) {
    var titles = document.querySelectorAll("[data-card-title]");
    var descriptions = document.querySelectorAll("[data-card-content]");
    var audios = document.querySelectorAll(".item-card audio");
    items.forEach(function (item, index) {
      if (titles[index]) titles[index].textContent = item.title;
      if (descriptions[index]) descriptions[index].textContent = item.description;
      if (audios[index]) {
        audios[index].src = "Audio/Kannada/" + encodePath(audioFiles[index]);
        audios[index].load();
      }
    });
    if (selector) selector.value = "kannada";
  }

  function renderItem(selector) {
    var itemNumber = Number((location.pathname.match(/item(\d+)\.html$/i) || [])[1]);
    if (!itemNumber) return;
    var item = items[itemNumber - 1];
    var section = document.getElementById("kannada");
    if (!section) {
      section = document.createElement("section");
      section.className = "bookContentDiv langCnt";
      section.id = "kannada";
      section.lang = "kn";
      section.innerHTML = '<h2 class="cntHdng"></h2><div class="booImgDiv"><img alt=""></div><div class="bookCntDiv"><p></p></div>';
      var firstSection = document.querySelector(".langCnt");
      firstSection.parentNode.insertBefore(section, firstSection);
    }
    section.querySelector(".cntHdng").textContent = item.title;
    section.querySelector("img").src = "Images/Glassgallery-item" + itemNumber + ".png";
    section.querySelector("img").alt = item.title;
    section.querySelector(".bookCntDiv p").textContent = item.description;
    document.querySelectorAll(".langCnt").forEach(function (element) {
      element.style.display = element.id === "kannada" ? "block" : "none";
    });
    var player = document.getElementById("languageAudio");
    if (player) {
      player.src = "Audio/Kannada/" + encodePath(audioFiles[itemNumber - 1]);
      player.load();
    }
    if (selector) selector.value = "kannada";
  }

  function applyKannada() {
    var selector = addLanguageOption();
    if (document.querySelector("[data-card-title]")) renderOverview(selector);
    else renderItem(selector);
  }

  var selector = addLanguageOption();
  if (selector) selector.addEventListener("change", function () {
    if (selector.value === "kannada") applyKannada();
  });
